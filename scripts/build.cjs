"use strict";
const fs = require("node:fs");
const path = require("node:path");

// Each execution world gets a complete private bundle. No browser-global module
// or cross-file initialization order is needed at runtime.
const root = path.resolve(__dirname, "..");
const core = fs.readFileSync(path.join(root, "core.js"), "utf8");
const output = path.join(root, "dist");
fs.mkdirSync(output, { recursive: true });
for (const entry of ["content.js", "page-bridge.js"]) {
  const source = fs.readFileSync(path.join(root, entry), "utf8");
  const code = `// Generated by scripts/build.cjs; edit the root sources instead.\n(() => {\n"use strict";\ntry {\nconst LeetcodeClearCore = (() => {\nconst module = { exports: {} };\n${core}\nreturn module.exports;\n})();\n${source}\n} catch (error) {\nconsole.error("[leetcode重做助手] ${entry} failed to start", error);\ndocument.dispatchEvent(new CustomEvent("lcr:controller-error", { detail: ${JSON.stringify(entry === "content.js" ? "自动处理脚本启动失败" : "页面适配脚本启动失败")} }));\n}\n})();\n`;
  fs.writeFileSync(path.join(output, entry), code, "utf8");
}
console.log("Built self-contained MAIN and ISOLATED scripts.");
